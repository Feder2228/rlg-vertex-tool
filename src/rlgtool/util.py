def vector_sum3(v1 : list[float], v2 : list[float], v3 : list[float]) -> list[float]:
    """Sum three vectors

    Args:
        v1: vector 1
        v2: vector 2
        v3: vector 3
    Returns:
        sum of the vectors
    """
    return [ v1[0] + v2[0] + v3[0], v1[1] + v2[1] + v3[1], v1[2] + v2[2] + v3[2]]

def vector_sub(v1 : list[float], v2 : list[float]) -> list[float]:
    return [ v1[0] - v2[0], v1[1] - v2[1], v1[2] - v2[2] ]

def dot_product(v1 : list[float], v2 : list[float]) -> list[float]:
    result = 0
    for i in range( len(v1) ):
        result += v1[i] * v2[i]
    return result

