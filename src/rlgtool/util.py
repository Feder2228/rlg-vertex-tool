def check_daepath(rlgpath : str) -> str:
    """Convert rlg filepath to a dae filepath

    Args:
        rlgpath: path of the rlg file
    Return:
        rlgpath + '.dae'
    """
    daepath = rlgpath + '.dae'
    if not os.path.isfile(daepath):
        return None
    return daepath




def check_rlgpath(daepath : str) -> str:
    """Convert dae filepath to a rlg filepath

    Args:
        daepath: path of the dae file
    Return:
        daepath - '.dae'
    """
    rlgpath = daepath[ :-4 ]
    if not os.path.isfile( rlgpath ):
        return None
    return rlgpath




